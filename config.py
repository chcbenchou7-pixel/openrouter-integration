import os
from dataclasses import dataclass, field
from typing import Dict, Optional, List
from enum import Enum


class ModelTier(Enum):
    """模型分級 - 用於路由決策"""
    FLAGSHIP = "flagship"      # 最強模型，成本高
    BALANCED = "balanced"      # 平衡性能與成本
    FAST_CHEAP = "fast_cheap"  # 極速廉價
    SPECIALIST = "specialist"  # 專用模型 (代碼/推理/視覺)
    FREE = "free"              # 免費模型


@dataclass
class ModelConfig:
    """單一模型配置"""
    model_id: str                    # OpenRouter 官方模型 ID
    tier: ModelTier                  # 分級
    max_tokens: int = 8192           # 最大輸出 tokens
    supports_tools: bool = True      # 支援 Function Calling
    supports_vision: bool = False    # 支援視覺/圖片輸入
    supports_reasoning: bool = False # 支援推理輸出 (如 o1, R1, GLM 等)
