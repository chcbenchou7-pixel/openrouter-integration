@dataclass
class OpenRouterConfig:
    """OpenRouter 客戶端總配置"""
    api_key: str
    base_url: str = "https://openrouter.ai/api/v1"
    app_name: str = "MyApp"
    app_url: str = "https://localhost"
    default_model: str = "deepseek-v3.2"  # 使用註冊表別名
    max_retries: int = 3
    timeout: float = 60.0
    # 成本控制
    max_cost_per_request: float = 1.0      # 單請求上限 $
    daily_budget: float = 10.0             # 每日預算 $
    # 觀測性
    log_requests: bool = True
    log_responses: bool = False

    @classmethod
    def from_env(cls, **overrides) -> "OpenRouterConfig":
        """從環境變數建立配置"""
        api_key = os.getenv("OPENROUTER_API_KEY")
        if not api_key:
            raise ValueError("OPENROUTER_API_KEY 環境變數未設定")
        return cls(
            api_key=api_key,
            app_name=os.getenv("OPENROUTER_APP_NAME", "MyApp"),
            app_url=os.getenv("OPENROUTER_APP_URL", "https://localhost"),
            **overrides,
        )